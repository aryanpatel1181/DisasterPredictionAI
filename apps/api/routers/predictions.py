from typing import List, Optional
from fastapi import APIRouter, Query, BackgroundTasks
from services.risk_engine.predictive_pipeline import predictor
from packages.schemas.hazard import NormalizedHazardEvent

router = APIRouter(prefix="/api/v1", tags=["AI Predictions & Upcoming Risks"])

@router.get("/predictions", summary="List Upcoming AI Disaster Risk Predictions & Forecast Windows")
async def get_upcoming_predictions(
    hazard_type: Optional[str] = Query(None, description="Filter by hazard type: flood, severe_weather, cyclone, earthquake, tsunami"),
    forecast_window: Optional[str] = Query(None, description="Filter prediction window: 6h, 12h, 24h, 72h"),
):
    """Returns AI probabilistic disaster risk predictions generated by trained XGBoost/LightGBM models across prediction windows."""
    predictions = predictor.generate_upcoming_disaster_predictions()

    if hazard_type:
        predictions = [p for p in predictions if p.hazard_type.value == hazard_type]

    if forecast_window:
        predictions = [
            p for p in predictions
            if p.forecast_end and (p.forecast_end - p.forecast_start).total_seconds() == int(forecast_window.replace("h", "")) * 3600
        ]

    return {
        "prediction_count": len(predictions),
        "status": "ACTIVE_AI_PREDICTIONS",
        "predictions": [p.model_dump() for p in predictions],
    }

@router.post("/predictions/train", summary="Train Disaster Models on Live Telemetry & Re-run Inference")
async def train_and_run_predictions():
    """Triggers ML model retraining on latest online hydro-meteorological data and updates AI risk estimates."""
    predictor._ensure_models_trained()
    new_preds = predictor.generate_upcoming_disaster_predictions()
    return {
        "status": "TRAINING_COMPLETE",
        "model_version": "flood_xgboost_v1.0",
        "generated_predictions_count": len(new_preds),
        "predictions": [p.model_dump() for p in new_preds],
    }
