const puppeteer = require('puppeteer');
const assert = require('node:assert/strict');
const url = process.env.GLOBE_TEST_URL || 'http://localhost:3000';

(async () => {
  const browser = await puppeteer.launch({headless: true, args: ['--enable-unsafe-swiftshader']});
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewport({width: 1440, height: 1000});
    await page.goto(url, {waitUntil: 'networkidle2'});
    const ready = () => page.waitForFunction(() => document.querySelector('.globe-canvas canvas')?.dataset.view && !document.querySelector('[aria-label="Zoom in globe"]').disabled);
    const view = () => page.$eval('.globe-canvas canvas', el => el.dataset.view);
    const zoom = async () => Number((await view()).split(',')[3]);
    await ready();
    let initial = await view();
    await page.waitForFunction(before => document.querySelector('.globe-canvas canvas').dataset.view !== before, {}, initial);
    await page.click('[aria-label="Pause globe rotation"]');
    const canvas = await page.$('.globe-canvas canvas');
    const box = await canvas.boundingBox();
    const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
    initial = await view();
    await page.mouse.move(cx, cy);
    await page.mouse.down();
    await page.mouse.move(cx + 85, cy + 30, {steps: 12});
    await page.mouse.up();
    assert.notEqual(await view(), initial, 'drag rotates sphere');
    let beforeZoom = await zoom();
    await page.mouse.wheel({deltaY: -160});
    await page.waitForFunction(before => Number(document.querySelector('.globe-canvas canvas').dataset.view.split(',')[3]) > before, {}, beforeZoom);
    await page.click('[aria-label="Reset globe view"]');
    await page.waitForFunction(() => document.querySelector('.globe-canvas canvas').dataset.view.endsWith(',1.0000'));
    initial = await view();
    await canvas.focus();
    await page.keyboard.press('ArrowLeft');
    await page.waitForFunction(before => document.querySelector('.globe-canvas canvas').dataset.view !== before, {}, initial);
    await page.keyboard.press('+');
    await page.waitForFunction(() => Number(document.querySelector('.globe-canvas canvas').dataset.view.split(',')[3]) > 1);
    for (let i = 0; i < 12; i++) await page.click('[aria-label="Zoom in globe"]');
    assert.ok(await zoom() <= 1.65, 'zoom maximum');
    for (let i = 0; i < 20; i++) await page.click('[aria-label="Zoom out globe"]');
    assert.ok(await zoom() >= 0.8, 'zoom minimum');
    await page.click('[aria-label="Reset globe view"]');
    await page.waitForFunction(() => document.querySelector('.globe-canvas canvas').dataset.view.endsWith(',1.0000'));
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.screenshot({path: 'work/hero-globe.png'});
    assert.ok(await page.evaluate(async () => {
      const canvas = document.querySelector('.globe-canvas canvas');
      const image = new Image();
      image.src = canvas.toDataURL();
      await image.decode();
      const sample = document.createElement('canvas');
      sample.width = sample.height = 1;
      const context = sample.getContext('2d');
      context.drawImage(image, canvas.width / 2, canvas.height / 2, 1, 1, 0, 0, 1, 1);
      return context.getImageData(0, 0, 1, 1).data[3] > 0;
    }), 'paused globe retains a visible rendered frame');
    await page.click('[aria-label="Resume globe rotation"]');
    await page.mouse.move(0, 0);
    await page.evaluate(() => document.activeElement.blur());
    initial = await view();
    await page.waitForFunction(before => document.querySelector('.globe-canvas canvas').dataset.view !== before, {timeout: 7000}, initial);
    await page.emulateMediaFeatures([{name: 'prefers-reduced-motion', value: 'reduce'}]);
    await page.waitForSelector('[aria-label="Resume globe rotation"]');
    await page.mouse.move(0, 0);
    await page.evaluate(() => document.activeElement.blur());
    await page.evaluate(() => new Promise(resolve => setTimeout(resolve, 1200)));
    initial = await view();
    await page.evaluate(() => new Promise(resolve => setTimeout(resolve, 4500)));
    assert.equal(await view(), initial, 'reduced motion remains still');
    await page.setViewport({width: 390, height: 844, isMobile: true, hasTouch: true});
    await ready();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const mobileCanvas = await page.$('.globe-canvas canvas');
    await mobileCanvas.scrollIntoView();
    const mobileBox = await mobileCanvas.boundingBox();
    const x = mobileBox.x + mobileBox.width / 2, y = mobileBox.y + mobileBox.height / 2;
    const cdp = await page.createCDPSession();
    const touch = (type, points) => cdp.send('Input.dispatchTouchEvent', {type, touchPoints: points.map(([x, y], id) => ({x, y, id}))});
    initial = await view();
    await touch('touchStart', [[x, y]]);
    await touch('touchMove', [[x + 60, y + 20]]);
    await touch('touchEnd', []);
    await page.waitForFunction(before => document.querySelector('.globe-canvas canvas').dataset.view !== before, {}, initial);
    beforeZoom = await zoom();
    await touch('touchStart', [[x - 35, y], [x + 35, y]]);
    await touch('touchMove', [[x - 65, y], [x + 65, y]]);
    await touch('touchEnd', []);
    await page.waitForFunction(before => Number(document.querySelector('.globe-canvas canvas').dataset.view.split(',')[3]) > before, {}, beforeZoom);
    await page.click('[aria-label="Reset globe view"]');
    await (await page.$('.orbital-art')).screenshot({path: 'work/hero-globe-mobile.png'});
    assert.deepEqual(errors, []);
    const fallback = await browser.newPage();
    await fallback.evaluateOnNewDocument(() => {
      const original = HTMLCanvasElement.prototype.getContext;
      HTMLCanvasElement.prototype.getContext = function(type, ...args) {
        return type.includes('webgl') ? null : original.call(this, type, ...args);
      };
    });
    await fallback.goto(url, {waitUntil: 'networkidle2'});
    await fallback.waitForSelector('[aria-label="Static Earth with country outlines"]');
    await fallback.waitForFunction(() => document.querySelector('.earth-borders')?.getAttribute('d')?.length > 1000);
    console.log('Hero globe passed: auto-rotation, drag, wheel, keyboard, reset, zoom limits, reduced motion, mobile drag/pinch, WebGL fallback, no runtime errors.');
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
